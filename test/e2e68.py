import sys; sys.path.insert(0,'test')
from seed import SEED
from playwright.sync_api import sync_playwright
PORT=sys.argv[1] if len(sys.argv)>1 else '8765'
fails=[]
def ok(c,m):
    print(('  ok  ' if c else '  FAIL ')+m)
    if not c: fails.append(m)
with sync_playwright() as p:
    b=p.chromium.launch(); ctx=b.new_context(viewport={'width':1400,'height':900}, service_workers='block'); pg=ctx.new_page()
    errs=[]; pg.on('pageerror', lambda e: errs.append(str(e)))
    pg.on('dialog', lambda d: d.accept())
    pg.goto(f'http://localhost:{PORT}/index.html'); pg.wait_for_timeout(400); pg.evaluate(SEED); pg.evaluate("sessionStorage.setItem('pp.asShown','1')")
    pg.evaluate("PP.store.set('xgAll',0);PP.store.set('hjAll',0)"); pg.reload(); pg.wait_for_timeout(700)
    # ---------- Hoje
    n=pg.evaluate("PP.assist.items().length")
    ok(n>=5,'o Hoje tem várias pendências para testar ('+str(n)+')')
    ok(pg.locator('#vHoje .hrow.hw').filter(visible=True).count()==3,'Hoje mostra só 3 pendências em destaque')
    ok(pg.locator('#vHoje details.hmais').count()==1 and f'Mais {n-3} pendência' in pg.inner_text('#vHoje details.hmais summary'),'as demais ficam em "Mais N pendências"')
    ok(not pg.evaluate("document.querySelector('#vHoje details.hmais').open"),'"Mais pendências" começa recolhido')
    ok(not pg.evaluate("document.querySelector('#vHoje details.hchart').open"),'o gráfico de vendas começa recolhido')
    pg.click('#vHoje details.hmais summary'); pg.wait_for_timeout(200)
    ok(pg.locator('#vHoje .hrow.hw').filter(visible=True).count()==n,'abrindo, aparecem todas as pendências')
    pg.evaluate("PP.hoje.render()"); pg.wait_for_timeout(200)
    ok(pg.evaluate("document.querySelector('#vHoje details.hmais').open"),'ao redesenhar, o que você abriu continua aberto')
    pg.click('#vHoje details.hchart summary'); pg.wait_for_timeout(200)
    ok(pg.locator('#vHoje details.hchart svg').first.is_visible(),'abrindo o gráfico, ele aparece')
    # ---------- Exportação
    pg.click('#nav [data-view="exp"]'); pg.wait_for_timeout(600)
    ok(pg.locator('details.xg').count()==4,'Exportação tem 4 blocos secundários agrupados')
    ok(pg.evaluate("[...document.querySelectorAll('details.xg')].filter(d=>d.open).map(d=>d.dataset.xg)")==['lpco'],'por padrão só o LPCO fica aberto (os outros recolhidos)')
    ok('package fee' in pg.inner_text('details.xg[data-xg=frete] summary').lower(),'o grupo recolhido mostra um resumo na linha')
    h1=pg.evaluate("document.documentElement.scrollHeight")
    pg.click('details.xg[data-xg=frete] summary'); pg.wait_for_timeout(200)
    ok(pg.locator('details.xg[data-xg=frete] [data-xp="ex.disc"]').is_visible(),'abrindo o grupo de frete/DOA, os campos aparecem')
    pg.click('[data-xdest="JPN"]'); pg.wait_for_timeout(500)
    ok(pg.evaluate("document.querySelector('details.xg[data-xg=frete]').open"),'trocar o destino (redesenha a tela) não fecha o grupo que você abriu')
    pg.click('[data-xa="xgall"]'); pg.wait_for_timeout(300)
    ok(pg.evaluate("[...document.querySelectorAll('details.xg')].every(d=>d.open)"),'"Abrir todos os blocos" abre os 4 grupos')
    h2=pg.evaluate("document.documentElement.scrollHeight")
    ok(h2>h1,'com tudo aberto a página fica mais alta ('+str(h2)+' > '+str(h1)+')')
    pg.click('[data-xa="xgall"]'); pg.wait_for_timeout(300)
    ok(pg.evaluate("[...document.querySelectorAll('details.xg')].filter(d=>d.open).map(d=>d.dataset.xg)")==['lpco'],'"Recolher blocos secundários" volta ao padrão')
    # ---------- Menu lateral
    ok(pg.locator('#nav .ngrp[data-ng]').count()==3,'o menu tem 3 seções clicáveis')
    ok(pg.locator('#nav [data-view="hist"]').count()==1,'Gestão começa aberta')
    pg.click('#nav .ngrp[data-ng="#ge"]'); pg.wait_for_timeout(200)
    ok(pg.locator('#nav [data-view="hist"]').count()==0 and pg.locator('#nav [data-view="financeiro"]').count()==0,'clicando em Gestão, os itens dela somem do menu')
    ok(pg.locator('#nav .ngrp[data-ng="#ge"]').get_attribute('aria-expanded')=='false','a seção marca aria-expanded=false')
    ok(pg.locator('#nav [data-view="exp"]').count()==1,'as outras seções continuam visíveis')
    pg.reload(); pg.wait_for_timeout(700)
    ok(pg.locator('#nav [data-view="hist"]').count()==0,'o menu recolhido é lembrado depois de recarregar')
    pg.evaluate("PP.go('hist')"); pg.wait_for_timeout(300)
    ok(pg.locator('#nav [data-view="hist"][aria-selected="true"]').count()==1,'a tela aberta aparece mesmo com a seção recolhida')
    pg.click('#nav .ngrp[data-ng="#ge"]'); pg.wait_for_timeout(200)
    ok(pg.locator('#nav [data-view="financeiro"]').count()==1,'clicando de novo, a seção reabre')
    ok(not errs,'sem erros de JavaScript: '+str(errs))
    b.close()
print('\nFALHAS:',len(fails)); sys.exit(1 if fails else 0)
