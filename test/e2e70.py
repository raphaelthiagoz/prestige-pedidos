import sys; sys.path.insert(0,'test')
from seed import SEED
from playwright.sync_api import sync_playwright
fails=[]
def ok(c,m):
    print(('  ok  ' if c else '  FAIL ')+m)
    if not c: fails.append(m)
PORT=sys.argv[1] if len(sys.argv)>1 else '8765'
with sync_playwright() as p:
    b=p.chromium.launch(); ctx=b.new_context(viewport={'width':1400,'height':900}, service_workers='block'); pg=ctx.new_page()
    errs=[]; pg.on('pageerror', lambda e: errs.append(str(e)))
    pg.goto(f'http://localhost:{PORT}/index.html'); pg.wait_for_timeout(400); pg.evaluate(SEED); pg.evaluate("sessionStorage.setItem('pp.asShown','1')"); pg.evaluate("PP.store.set('bkSnooze',Date.now()+9e9)"); pg.reload(); pg.wait_for_timeout(600)
    ok(pg.locator('#btnGuia').count()==1,'o menu lateral tem o botão "Manual e tour"')
    ok(pg.locator('#btnGuia.novo').count()==1,'o botão mostra "novo" até a primeira abertura')
    # --- manual
    pg.click('#btnGuia'); pg.wait_for_timeout(300)
    ok(pg.locator('#guiaMod[role=dialog]').count()==1,'o manual abre como janela')
    ok(pg.locator('#guiaTxt .gSec').count()>=10,'o manual tem as seções (>=10): %d'%pg.locator('#guiaTxt .gSec').count())
    ok(pg.locator('#btnGuia.novo').count()==0,'depois de aberto o "novo" some')
    pg.fill('#guiaQ','backup'); pg.wait_for_timeout(200)
    t=pg.inner_text('#guiaTxt')
    ok('Baixar backup' in t and pg.locator('#guiaTxt .gSec').count()<pg.evaluate("PP.guia.SEC.length"),'a busca "backup" filtra as seções')
    pg.fill('#guiaQ','zzzxxx'); pg.wait_for_timeout(200)
    ok('Nada encontrado' in pg.inner_text('#guiaTxt'),'busca sem resultado avisa')
    pg.fill('#guiaQ','sei'); pg.wait_for_timeout(200)
    ok('Notas de entrada e MAPA' in pg.inner_text('#guiaTxt'),'busca "sei" acha Notas de entrada e MAPA')
    pg.keyboard.press('Escape'); pg.wait_for_timeout(200)
    ok(pg.locator('#guiaMod').count()==0,'Esc fecha o manual')
    # --- tour
    pg.click('#btnGuia'); pg.wait_for_timeout(200); pg.click('#guiaTour'); pg.wait_for_timeout(300)
    ok(pg.locator('#tourCard').count()==1 and pg.locator('#guiaMod').count()==0,'"Iniciar tour guiado" fecha o manual e abre o tour')
    n=pg.evaluate("PP.guia.STEPS.length")
    ok('Passo 1 de %d'%n in pg.text_content('#tourCard'),'começa no passo 1 de %d'%n)
    ok(pg.locator('[data-t=volta]').count()==0,'no primeiro passo não há "Voltar"')
    pg.click('#tourNext'); pg.wait_for_timeout(350)
    ok('Hoje' in pg.text_content('#tourCard') and pg.locator('#tourShade:not(.full)').count()==1,'passo 2 destaca o item "Hoje" do menu')
    box=pg.evaluate("(()=>{const s=document.getElementById('tourShade').getBoundingClientRect(),t=document.querySelector('#nav [data-view=hoje]').getBoundingClientRect();return Math.abs(s.left-t.left)<8&&Math.abs(s.top-t.top)<8&&s.width>=t.width})()")
    ok(box,'o destaque está em cima do botão certo')
    cardBox=pg.evaluate("(()=>{const c=document.getElementById('tourCard').getBoundingClientRect();return c.left>=0&&c.top>=0&&c.right<=innerWidth&&c.bottom<=innerHeight})()")
    ok(cardBox,'o cartão do tour fica inteiro dentro da tela')
    pg.click('[data-t=volta]'); pg.wait_for_timeout(250)
    ok('Passo 1 de' in pg.text_content('#tourCard'),'Voltar retorna ao passo 1')
    pg.keyboard.press('ArrowRight'); pg.wait_for_timeout(250)
    ok('Passo 2 de' in pg.text_content('#tourCard'),'seta direita avança')
    # percorre todos
    for i in range(n-2): pg.click('#tourNext'); pg.wait_for_timeout(200)
    ok('Passo %d de %d'%(n,n) in pg.text_content('#tourCard'),'chega ao último passo')
    ok(pg.locator('[data-t=manual]').count()==1,'o último passo oferece "Abrir o manual"')
    pg.click('#tourNext'); pg.wait_for_timeout(250)
    ok(pg.locator('#tourCard').count()==0 and pg.locator('#tourShade').count()==0,'Concluir fecha o tour')
    ok(pg.evaluate("PP.store.get('tourVisto',0)")==1,'o app lembra que o tour foi feito')
    # Esc no meio
    pg.evaluate("PP.guia.startTour(3)"); pg.wait_for_timeout(300)
    ok('Passo 4 de' in pg.text_content('#tourCard'),'dá para começar de um passo específico')
    pg.keyboard.press('Escape'); pg.wait_for_timeout(250)
    ok(pg.locator('#tourCard').count()==0,'Esc sai do tour')
    # item de menu oculto/recolhido não quebra
    pg.evaluate("PP.store.set('navCol',{'#op':1})"); pg.reload(); pg.wait_for_timeout(600)
    pg.evaluate("PP.guia.startTour(2)"); pg.wait_for_timeout(300)
    ok(pg.locator('#tourShade.full').count()==1 and pg.locator('#tourCard').count()==1,'menu recolhido: o tour mostra o cartão no centro, sem erro')
    pg.keyboard.press('Escape')
    # celular
    pg.set_viewport_size({'width':390,'height':780}); pg.wait_for_timeout(300)
    pg.evaluate("PP.guia.openManual()"); pg.wait_for_timeout(300)
    ok(pg.evaluate("(()=>{const b=document.querySelector('.guiaBox').getBoundingClientRect();return b.left>=0&&b.right<=innerWidth})()"),'no celular o manual cabe na tela')
    ok(not errs,'sem erro de JS: '+str(errs))
    b.close()
print('FALHAS:',fails) if fails else print('TUDO OK')
sys.exit(1 if fails else 0)
